import { build } from "esbuild";
import { writeFile } from "node:fs/promises";
const result = await build({
  entryPoints: ["src/guest.ts"],
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  target: "es2022",
  metafile: true,
  alias: { "@octogen-ai/sdk": "../sdks/typescript/src/index.ts" },
  minify: true,
});
// esbuild's browser platform rejects any transitive node: import. No Node shims.
if (
  Object.keys(result.metafile.inputs).some((p) =>
    /node-host|\/version\.ts|\/auth\.ts/.test(p),
  )
)
  throw new Error("Node adapter reached guest");
await writeFile(
  "src/core-source.generated.ts",
  `// Generated by tools/bundle-core.mjs; do not edit.\nexport default ${JSON.stringify(result.outputFiles[0].text)};\n`,
);
