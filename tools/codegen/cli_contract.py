"""Generate CLI runtime request schemas from the public snapshot (no network)."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path


def render(spec: dict) -> str:
    def resolve(node: object, trail: tuple[str, ...] = ()) -> object:
        if isinstance(node, list):
            return [resolve(item, trail) for item in node]
        if not isinstance(node, dict):
            return node
        if "$ref" in node:
            ref = node["$ref"]
            if not ref.startswith("#/components/schemas/") or ref in trail:
                raise ValueError(f"Unsupported request reference: {ref}")
            target = spec["components"]["schemas"][ref.rsplit("/", 1)[1]]
            return resolve(
                {**target, **{k: v for k, v in node.items() if k != "$ref"}},
                (*trail, ref),
            )
        return {k: resolve(v, trail) for k, v in node.items()}

    def check_schema(schema: dict) -> None:
        supported = {
            "type",
            "properties",
            "required",
            "additionalProperties",
            "anyOf",
            "enum",
            "items",
            "default",
            "description",
            "title",
            "minimum",
            "maximum",
            "minLength",
            "maxLength",
            "minItems",
            "maxItems",
            "examples",
            "deprecated",
        }
        unknown = schema.keys() - supported
        if unknown:
            raise ValueError(
                f"CLI validator needs support for schema keywords: {sorted(unknown)}"
            )
        if schema.get("type") not in {
            None,
            "null",
            "boolean",
            "string",
            "integer",
            "number",
            "array",
            "object",
        }:
            raise ValueError("CLI validator needs support for schema type")
        if not isinstance(schema.get("additionalProperties", True), bool):
            raise ValueError(
                "CLI validator needs support for schema-valued additionalProperties"
            )
        for child in schema.get("properties", {}).values():
            check_schema(child)
        for child in schema.get("anyOf", []):
            check_schema(child)
        if "items" in schema:
            check_schema(schema["items"])

    operations = {}
    for path, item in spec["paths"].items():
        for method, operation in item.items():
            if method not in {
                "get",
                "post",
                "put",
                "patch",
                "delete",
                "head",
                "options",
                "trace",
            }:
                continue
            name = operation["operationId"]
            if name in operations:
                raise ValueError(f"Duplicate public operation: {name}")
            parameters = []
            for parameter in item.get("parameters", []) + operation.get(
                "parameters", []
            ):
                if "$ref" in parameter:
                    ref = parameter["$ref"]
                    if not ref.startswith("#/components/parameters/"):
                        raise ValueError(f"Unsupported parameter reference: {ref}")
                    parameter = spec["components"]["parameters"][ref.rsplit("/", 1)[1]]
                # Header metadata (including JSON-content RequestContext) is
                # handled by SDK request options, not CLI body/query arguments.
                if parameter["in"] in {"path", "query"}:
                    parameters.append(parameter)
            body = (
                operation.get("requestBody", {})
                .get("content", {})
                .get("application/json", {})
                .get("schema", {"type": "object", "properties": {}})
            )
            check_schema(resolve(body))
            for parameter in parameters:
                check_schema(resolve(parameter["schema"]))
            operations[name] = {
                "method": method.upper(),
                "path": path,
                "body": resolve(body),
                "parameters": [
                    {**p, "schema": resolve(p["schema"])} for p in parameters
                ],
            }
    digest = hashlib.sha256(
        (json.dumps(spec, sort_keys=True, indent=2, ensure_ascii=False) + "\n").encode()
    ).hexdigest()
    payload = {
        "version": spec["info"]["version"],
        "sha256": digest,
        "operations": operations,
    }
    return (
        "/** Generated by npm run codegen from the public v1 snapshot. "
        "Do not edit. */\n"
        "export const PUBLIC_CONTRACT = "
        + json.dumps(payload, indent=2, sort_keys=True, ensure_ascii=False)
        + " as const;\n"
    )


def generate(snapshot: Path, destination: Path) -> None:
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(render(json.loads(snapshot.read_text())), encoding="utf-8")
